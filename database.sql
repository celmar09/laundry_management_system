CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL, username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('super_admin','admin','staff') NOT NULL DEFAULT 'staff',
 active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS customers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(140) NOT NULL,
 phone VARCHAR(40), email VARCHAR(140), address TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX(name), INDEX(phone)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS services (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE,
 description TEXT, unit ENUM('kg','item','load') NOT NULL DEFAULT 'kg',
 price DECIMAL(10,2) NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, tracking_code VARCHAR(30) NOT NULL UNIQUE,
 customer_id INT UNSIGNED NOT NULL, status ENUM('Received','Washing','Drying','Ready for Pickup','Completed') NOT NULL DEFAULT 'Received',
 received_at DATETIME NOT NULL, estimated_completion DATETIME NULL, ready_since DATETIME NULL,
 subtotal DECIMAL(10,2) NOT NULL DEFAULT 0, discount DECIMAL(10,2) NOT NULL DEFAULT 0,
 extra_charge DECIMAL(10,2) NOT NULL DEFAULT 0, total DECIMAL(10,2) NOT NULL DEFAULT 0,
 notes TEXT, created_by INT UNSIGNED NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES customers(id), FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL,
 INDEX(status), INDEX(received_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 service_id INT UNSIGNED NULL, service_name VARCHAR(120) NOT NULL,
 quantity DECIMAL(10,2) NOT NULL DEFAULT 1, unit VARCHAR(12) NOT NULL DEFAULT 'kg',
 unit_price DECIMAL(10,2) NOT NULL DEFAULT 0, line_total DECIMAL(10,2) NOT NULL DEFAULT 0,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(service_id) REFERENCES services(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_status_history (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 status VARCHAR(40) NOT NULL, note VARCHAR(255), changed_by INT UNSIGNED NULL,
 changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(changed_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL,
 amount DECIMAL(10,2) NOT NULL, method ENUM('Cash','GCash','Bank Transfer','Other') NOT NULL DEFAULT 'Cash',
 reference_no VARCHAR(100), received_by INT UNSIGNED NULL, paid_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY(received_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS expenses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(160) NOT NULL,
 category VARCHAR(80), amount DECIMAL(10,2) NOT NULL, expense_date DATE NOT NULL,
 notes TEXT, created_by INT UNSIGNED NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS inventory (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, item_name VARCHAR(140) NOT NULL,
 category VARCHAR(80), unit VARCHAR(30) NOT NULL DEFAULT 'pcs',
 quantity DECIMAL(10,2) NOT NULL DEFAULT 0, reorder_level DECIMAL(10,2) NOT NULL DEFAULT 0,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, inventory_id INT UNSIGNED NOT NULL,
 movement ENUM('Stock In','Stock Out') NOT NULL, quantity DECIMAL(10,2) NOT NULL,
 notes VARCHAR(255), user_id INT UNSIGNED NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(inventory_id) REFERENCES inventory(id), FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS machines (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL,
 machine_type VARCHAR(60), status ENUM('Available','In Use','Maintenance') NOT NULL DEFAULT 'Available',
 notes TEXT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (
 setting_key VARCHAR(100) PRIMARY KEY, setting_value TEXT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS activity_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NULL,
 action VARCHAR(180) NOT NULL, details TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
